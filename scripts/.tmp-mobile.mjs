import puppeteer from 'puppeteer-core';
const [out] = process.argv.slice(2);
const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const p = await b.newPage();
await p.setViewport({ width: 360, height: 740, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await p.goto('http://localhost:4317/#work', { waitUntil: 'networkidle0' });
const tabs = await p.$('[aria-label="Filter projects by platform"]');
await tabs.evaluate((el) => el.scrollIntoView({ block: 'center' }));
await new Promise((r) => setTimeout(r, 1200));
const info = await tabs.evaluate((el) => ({ client: el.clientWidth, scroll: el.scrollWidth, height: el.offsetHeight, docOverflow: document.documentElement.scrollWidth > innerWidth }));
console.log(JSON.stringify(info));
await p.screenshot({ path: out + '/tabs-start.png' });
const mern = (await p.$$('[aria-label="Filter projects by platform"] button')).at(-1);
await mern.click();
await new Promise((r) => setTimeout(r, 800));
await p.screenshot({ path: out + '/tabs-mern.png' });
await b.close();
